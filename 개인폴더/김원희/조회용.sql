SELECT 
    A.EMPLOYER_NO AS employerNo,
    B.MEMBERSHIP_TYPE AS membershipType
FROM EMPLOYER A
JOIN MEMBERSHIP B ON A.EMPLOYER_NO = B.EMPLOYER_NO
WHERE A.EMPLOYER_NO = 2
  AND B.MEMBERSHIP_DEL_FL = 'N';

 
 SELECT 
    A.EMPLOYER_NO AS employerNo,
    B.MEMBERSHIP_TYPE AS membershipType,
    B.MEMBERSHIP_CONTENT AS membershipContent
FROM EMPLOYER A
JOIN MEMBERSHIP B ON A.EMPLOYER_NO = B.EMPLOYER_NO
WHERE A.EMPLOYER_NO = 3
  AND B.MEMBERSHIP_DEL_FL = 'N';
  
SELECT 
    A.EMPLOYER_NO AS employerNo,
    B.MEMBERSHIP_TYPE AS membershipType,
    B.MEMBERSHIP_CONTENT AS membershipContent,
    (TRUNC(B.MEMBERSHIP_END_DATE) - TRUNC(B.MEMBERSHIP_START_DATE)) || '일' AS exp_Days
FROM EMPLOYER A
JOIN MEMBERSHIP B ON A.EMPLOYER_NO = B.EMPLOYER_NO
WHERE A.EMPLOYER_NO = 4
