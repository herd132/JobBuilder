SELECT *
FROM (
    SELECT DISTINCT
        TO_CHAR(C.PAYMENT_DATE, 'YYYY-MM-DD HH24:MI:SS') AS PAYMENT_DATE,
        C.PAYMENT_NO AS PAYMENT_NO,
        C.PAYMENT_PRODUCT AS PAYMENT_PRODUCT,
        C.PAYMENT_AMOUNT AS PAYMENT_AMOUNT,
        C.PAYMENT_STATUS AS PAYMENT_STATUS,
        D.PAYMENT_TYPE_AMOUNT AS PAYMENT_TYPE_AMOUNT,
        D.PAYMENT_TYPE_PRODUCT AS PAYMENT_TYPE_PRODUCT,
        TO_CHAR(D.PAYMENT_TYPE_CREATE_DATE, 'YYYY-MM-DD HH24:MI:SS') AS PAYMENT_TYPE_CREATE_DATE
    FROM 
        EMPLOYER E
    JOIN 
        MEMBERSHIP A ON E.EMPLOYER_NO = A.EMPLOYER_NO
    JOIN 
        PAYMENT_MEMBERSHIP B ON A.MEMBERSHIP_NO = B.MEMBERSHIP_NO
    JOIN 
        PAYMENT C ON B.PAYMENT_NO = C.PAYMENT_NO
    JOIN 
        PAYMENT_TYPE D ON C.PAYMENT_NO = D.PAYMENT_NO
    WHERE 
        E.EMPLOYER_NO = 3
) T
ORDER BY T.PAYMENT_DATE DESC;



	 SELECT 
    A.GRADE_NO AS GRADE_NO,
    A.MODIFICATION_DATE AS MODIFICATION_DATE,
    A.PERIOD_NO AS PERIOD_NO,
    A.REGISTRATION_DATE AS REGISTRATION_DATE,
    A.RESUME_CONTENT AS RESUME_CONTENT,
    A.RESUME_DEL_FL AS RESUME_DEL_FL,
    A.RESUME_DEL_FL AS RESUME_HIDE_FL,
    A.RESUME_NO AS RESUME_NO,
    A.RESUME_TITLE AS RESUME_TITLE,
    A.SALARY_AMOUNT AS SALARY_AMOUNT,
    A.SALARY_NO AS SALARY_NO,
    A.WORKCOND_ADDRESS_NO AS WORKCOND_ADDRESS_NO,
    A.WORKER_NO AS WORKER_NO,
    B.WORKCOND_ADDRESS_TYPE_NO AS WORKCOND_ADDRESS_TYPE_NO,
    C.WORKCOND_ADDRESS_TYPE_INFO AS WORKCOND_ADDRESS_TYPE_INFO,
    (
        SELECT 
            NVL(SUM(
                CASE 
                    WHEN CI.END_DATE IS NULL THEN TRUNC(SYSDATE) - TRUNC(CI.START_DATE)
                    ELSE TRUNC(CI.END_DATE) - TRUNC(CI.START_DATE)
                END
            ), 0)
        FROM 
            RESUME_CAREER RC
        JOIN 
            CAREER_INFO CI
        ON 
            RC.CAREER_NO = CI.CAREER_NO
        WHERE 
            RC.RESUME_NO = A.RESUME_NO
    ) AS TOTAL_CAREER
FROM 
    RESUME A
LEFT JOIN 
    WORKCOND_ADDRESS B
ON 
    A.WORKCOND_ADDRESS_NO = B.WORKCOND_ADDRESS_NO
LEFT JOIN 
    WORKCOND_ADDRESS_TYPE C
ON 
    B.WORKCOND_ADDRESS_TYPE_NO = C.WORKCOND_ADDRESS_TYPE_NO
WHERE 
    A.WORKER_NO = 9
    AND A.RESUME_DEL_FL = 'N'
ORDER BY 
    A.RESUME_NO DESC;




SELECT 
    R.WORKER_NO,
    R.RESUME_NO,
    SUM(
        CASE 
            WHEN CI.END_DATE IS NULL THEN TRUNC(SYSDATE) - TRUNC(CI.START_DATE) -- 종료일이 NULL인 경우 현재 날짜 사용
            ELSE TRUNC(CI.END_DATE) - TRUNC(CI.START_DATE) -- 종료일이 있는 경우 종료일 - 시작일 계산
        END
    ) AS TOTAL_DAYS
FROM 
    RESUME R
JOIN 
    RESUME_CAREER RC
    ON R.RESUME_NO = RC.RESUME_NO
JOIN 
    CAREER_INFO CI
    ON RC.CAREER_NO = CI.CAREER_NO
WHERE 
    R.WORKER_NO = 9
    AND R.RESUME_NO = 41
GROUP BY 
    R.WORKER_NO, R.RESUME_NO;




