----- 사업장 이미지 테이블 별도로 추가 + 코멘트 + 제약조건

CREATE TABLE "BUSINESS_IMG" (
	"BUSINESS_IMG_NO"	NUMBER		NOT NULL,
	"BUSINESS_IMG_PATH"	VARCHAR2(200)		NOT NULL,
	"BUSINESS_IMG_ORIGINAL_NAME"	NVARCHAR2(50)		NOT NULL,
	"BUSINESS_IMG_RENAME"	NVARCHAR2(50)		NOT NULL,
	"BUSINESS_IMG_ORDER"	NUMBER		NULL,
	"EMPLOYER_NO"	NUMBER		NOT NULL
);

COMMENT ON COLUMN "BUSINESS_IMG"."BUSINESS_IMG_NO" IS '이미지 번호(PK)';
COMMENT ON COLUMN "BUSINESS_IMG"."BUSINESS_IMG_PATH" IS '이미지 경로';
COMMENT ON COLUMN "BUSINESS_IMG"."BUSINESS_IMG_ORIGINAL_NAME" IS '이미지 원본명';
COMMENT ON COLUMN "BUSINESS_IMG"."BUSINESS_IMG_RENAME" IS '이미지 변경명';
COMMENT ON COLUMN "BUSINESS_IMG"."BUSINESS_IMG_ORDER" IS '이미지 순서';
COMMENT ON COLUMN "BUSINESS_IMG"."EMPLOYER_NO" IS '고용주번호(FK)';

ALTER TABLE "BUSINESS_IMG" ADD CONSTRAINT "PK_BUSINESS_IMG" PRIMARY KEY (
	"BUSINESS_IMG_NO"
);

ALTER TABLE "BUSINESS_IMG" ADD CONSTRAINT "FK_EMPLOYER_TO_BUSINESS_IMG_1" FOREIGN KEY (
	"EMPLOYER_NO"
)
REFERENCES "EMPLOYER" (
	"EMPLOYER_NO"
);

