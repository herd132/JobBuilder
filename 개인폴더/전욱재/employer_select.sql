SELECT e.MEMBER_NO, EMPLOYER_NO, 
	BUSINESS_REGISTRATION_NUMBER, BUSINESS_NAME, BUSINESS_ADDRESS, BUSINESS_NICKNAME,
	MEMBERSHIP_LEVEL, MEMBERSHIP_NAME,
	MEMBER_EMAIL, MEMBER_PW, MEMBER_NAME, MEMBER_TEL,
	TO_CHAR(ENROLL_DATE, 'YYYY"년" MM"월" DD"일" HH24"시" MI"분" SS"초"') ENROLL_DATE,
	m.AUTHORITY_NO, AUTHORITY_NAME
